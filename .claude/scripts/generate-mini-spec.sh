#!/bin/bash
# Generate Mini Spec - Background Draft Spec Generator
# Called asynchronously by workflow-guide.sh to create spec drafts
# Usage: generate-mini-spec.sh "user prompt"

set -euo pipefail

PROMPT="$1"

# Project directory from environment or exit
PROJECT_DIR="${CLAUDE_PROJECT_DIR:-}"
if [ -z "$PROJECT_DIR" ]; then
    exit 0
fi

# Spec directory
SPEC_DIR="$PROJECT_DIR/.specify"
DRAFT_FILE="$SPEC_DIR/spec.draft.md"

# Create spec directory if needed
mkdir -p "$SPEC_DIR"

# Extract key information from prompt
extract_feature_name() {
    local prompt="$1"
    # Extract first meaningful phrase (Korean or English)
    echo "$prompt" | grep -oE '(implement|create|add|build|write|generate).{1,30}' | head -1 | sed 's/^[^[:alnum:]]*//' || \
    echo "$prompt" | grep -oE '(implement|create|add|build|write).{1,30}' | head -1 | sed 's/^[^[:alnum:]]*//' || \
    echo "New Feature"
}

FEATURE_NAME=$(extract_feature_name "$PROMPT")
TIMESTAMP=$(date +%Y-%m-%d)

# Generate draft spec
cat > "$DRAFT_FILE" << EOF
# Feature Spec Draft (Auto-generated)

**Generated**: $TIMESTAMP
**Status**: Draft - Requires Review

## Original Request

$PROMPT

## Feature Summary

$FEATURE_NAME

## Scope (To Be Defined)

- [ ] Core functionality
- [ ] User interface changes
- [ ] API/Backend changes
- [ ] Testing requirements

## Technical Considerations

> This is an auto-generated draft. Use \`/specify\` to refine.

## Acceptance Criteria

1. TBD

---

*Auto-generated by VVCS workflow-guide hook*
EOF

exit 0
